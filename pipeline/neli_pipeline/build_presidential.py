"""Build the presidential-by-state dataset from cached sources.

    uv run python -m neli_pipeline.build_presidential [--refresh]

Writes (committed, so the app and Anyanwụ can use them without network access):
  data/processed/presidential_state_votes.csv   one row per year x state x candidate
  data/processed/presidential_state_summary.csv one row per year x state (valid/rejected/total)
  data/processed/presidential_national.csv      declared national totals vs the sum of states
  data/processed/VALIDATION_presidential.md     human-readable checks and known gaps
and records each source's exact revision in data/sources/manifest.json.
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from .extract.presidential import extract
from .paths import PROCESSED
from .sources import wikipedia as wp
from .states import STATES

# Years with a by-state table on Wikipedia. 2007 and 2011 have none there (see GAPS).
YEARS = [1999, 2003, 2015, 2019, 2023]
GAPS = {
    2007: "No accessible state-level source yet (no by-state table on English, French or German Wikipedia; African Elections Database offline; Internet Archive unreachable from the build environment). Needs INEC's 2007 results or another archive.",
    2011: "Same as 2007: Wikipedia has national totals only; state-level figures need INEC's 2011 results or another archive.",
}


def build(refresh: bool = False) -> int:
    votes, summaries, national, notes = [], [], [], []
    for year in YEARS:
        title = f"{year}_Nigerian_presidential_election"
        html = wp.fetch(title, refresh=refresh)
        src = wp.record(f"wikipedia:presidential:{year}", title, html)
        ex = extract(html, year)
        v = ex.votes.assign(source=src.key)
        votes.append(v)
        summaries.append(ex.states.assign(source=src.key))

        by_cand = (
            v.groupby(["candidate", "party", "lineage"], as_index=False)["votes"].sum().rename(columns={"votes": "state_sum"})
        )
        by_cand["declared"] = by_cand["candidate"].map(ex.total_row)
        by_cand["difference"] = by_cand["state_sum"] - by_cand["declared"]
        by_cand.insert(0, "year", year)
        national.append(by_cand)

        diffs = by_cand.dropna(subset=["declared"])
        worst = diffs.loc[diffs["difference"].abs().idxmax()] if len(diffs) else None
        exact = bool(len(diffs)) and (diffs["difference"] == 0).all()
        notes.append(
            (
                year,
                src.revision,
                len(ex.states),
                exact,
                None if worst is None or exact else (worst["candidate"], int(worst["difference"]), worst["declared"]),
            )
        )

    votes_df = pd.concat(votes, ignore_index=True)
    names = {c: n for c, (n, _) in STATES.items()}
    zones = {c: z for c, (_, z) in STATES.items()}
    votes_df.insert(2, "state", votes_df["state_code"].map(names))
    votes_df.insert(3, "zone", votes_df["state_code"].map(zones))
    summary_df = pd.concat(summaries, ignore_index=True)
    national_df = pd.concat(national, ignore_index=True).sort_values(["year", "declared"], ascending=[True, False])

    PROCESSED.mkdir(parents=True, exist_ok=True)
    votes_df.to_csv(PROCESSED / "presidential_state_votes.csv", index=False)
    summary_df.to_csv(PROCESSED / "presidential_state_summary.csv", index=False)
    national_df.to_csv(PROCESSED / "presidential_national.csv", index=False)
    _report(notes, national_df)
    print(f"wrote {len(votes_df)} vote rows, {len(summary_df)} state rows for {YEARS}; gaps: {sorted(GAPS)}")
    return 0


def _report(notes, national_df: pd.DataFrame) -> None:
    lines = [
        "# Presidential results by state: validation",
        "",
        "Generated by `neli_pipeline.build_presidential`. Source: Wikipedia articles (exact revisions in",
        "`data/sources/manifest.json`), which transcribe INEC's declared results with citations.",
        "",
        "Check: the sum of the 37 state rows for each candidate vs the table's own national total",
        "(which matches INEC's declared result).",
        "",
        "| Year | Revision | States | Sum of states = declared total? |",
        "|---|---|---|---|",
    ]
    for year, rev, n, exact, worst in notes:
        status = (
            "Yes, exactly"
            if exact
            else (f"No: largest gap {worst[0]} {worst[1]:+,} ({worst[1] / worst[2]:+.2%})" if worst else "No declared totals")
        )
        lines.append(f"| {year} | {rev} | {n} | {status} |")
    lines += ["", "## Gaps", ""]
    lines += [f"- **{y}:** {why}" for y, why in GAPS.items()]
    lines += [
        "",
        "## Notes",
        "",
        "- Party labels come from each article's national results table, matched to the by-state columns by candidate name.",
        "- `lineage` maps historical parties to today's (e.g. ANPP, ACN, CPC, AD, APP → APC), for modelling continuity; the ballot label is kept in `party`.",
        "- Coverage of per-state totals varies: 1999 has total votes only; 2003 has valid, rejected and total; 2015 has none;",
        "  2019 and 2023 have valid votes. No year carries registered voters by state; those come next from INEC's registers",
        "  (needed for turnout and for the live model's estimate of votes still to come).",
        "",
        "## Declared national totals vs sum of states",
        "",
        national_df.head(60).to_markdown(index=False)
        if hasattr(national_df, "to_markdown")
        else national_df.head(60).to_string(index=False),
        "",
    ]
    (PROCESSED / "VALIDATION_presidential.md").write_text("\n".join(lines))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--refresh", action="store_true", help="re-download sources instead of using the cache")
    sys.exit(build(p.parse_args().refresh))
